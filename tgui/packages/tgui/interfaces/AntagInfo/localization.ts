import { usePreferencesLocalization } from '../localization';

export type AntagInfoLanguage = 'en' | 'ru';

export type AntagInfoLocale = {
  lang: AntagInfoLanguage;
};

export function useAntagInfoLocale(): AntagInfoLocale {
  const { data } = useBackend<Record<string, unknown>>();
  const { language } = usePreferencesLocalization(data, 'antag_info');

  return {
    lang: language === 'russian' ? 'ru' : 'en',
  };
}
